export function encodeCp850(value: string, replacement = 0x3f): Uint8Array {
  const output: number[] = []
  Array.from(value).forEach((character) => {
    const code = character.codePointAt(0) ?? replacement
    if (code <= 0x7f) output.push(code)
    else output.push(CP850_EXTENDED[character] ?? replacement)
  })
  return Uint8Array.from(output)
}

export function cp850Byte(character: string): number | null {
  if (character.length !== 1) return null
  const code = character.codePointAt(0) ?? -1
  if (code >= 0 && code <= 0x7f) return code
  return CP850_EXTENDED[character] ?? null
}
